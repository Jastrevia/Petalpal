// Per-owner opt-in, PETAL_CARDS_OWNER_IDS (comma-separated PetalPal user ids, or "*" alone
// for every owner; spaces and line breaks around them are ignored).
// Unset, empty or malformed: nobody; the Weekly report is otherwise unchanged.
const MAX_OWNERS = 100;
export const petalCardsEnabledFor = (env, userId) => ownerListIncludes(env?.PETAL_CARDS_OWNER_IDS, userId);
// The same list format, for other per-owner switches (PETAL_READING_OWNER_IDS).
export function ownerListIncludes(value, userId) {
  const raw = typeof value === "string" ? value.trim() : "";
  if (!raw) return false;
  if (raw === "*") return typeof userId === "string" && userId.length > 0;
  const ids = raw.split(",").map(id => id.trim());
  if (ids.length > MAX_OWNERS || ids.some(id => !/^[A-Za-z0-9_-]{1,64}$/.test(id))) return false;
  return ids.includes(userId);
}
